AOZORA_SAMPLE = (
    "吾輩は猫である\n"
    "夏目漱石\n"
    "\n"
    "-------------------------------------------------------\n"
    "【テキスト中に現れる記号について】\n"
    "《》：ルビ\n"
    "-------------------------------------------------------\n"
    "吾輩《わがはい》は猫である。｜名前《なまえ》はまだ無い。\n"
    "　どこで生れたか［＃「生れた」に傍点］見当がつかぬ。\n"
    "\n"
    "底本：「吾輩は猫である」岩波書店\n"
    "入力：青空文庫\n"
)


def _aozora_zip_bytes(text: str = AOZORA_SAMPLE) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        zf.writestr("sample.txt", text.encode("cp932"))
    return buf.getvalue()


class _FakeResponse:
    def __init__(self, payload: bytes) -> None:
        self._payload = payload

    def read(self) -> bytes:
        return self._payload

    def __enter__(self) -> _FakeResponse:
        return self

    def __exit__(self, exc_type: object, exc: object, tb: object) -> None:
        return None


class _StaticOpener:
    def __init__(self, payload: bytes) -> None:
        self._payload = payload

    def open(self, url: str, timeout: float = 30.0) -> _FakeResponse:
        return _FakeResponse(self._payload)


