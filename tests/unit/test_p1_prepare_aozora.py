def test_prepare_aozora_corpora_writes_cleaned_utf8_files(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    payload = _aozora_zip_bytes()
    monkeypatch.setattr(
        p1_prepare_aozora.urllib.request,
        "build_opener",
        lambda *handlers: _StaticOpener(payload),
    )
    records = p1_prepare_aozora.prepare_aozora_corpora(
        ["https://www.aozora.gr.jp/cards/000148/files/789_ruby_5639.zip"],
        out_dir=tmp_path,
    )
    assert len(records) == 1
    output_path = Path(records[0]["path"])
    assert output_path.exists()
    text = output_path.read_text(encoding="utf-8")
    assert "名前はまだ無い。" in text
    assert "《" not in text
    assert records[0]["chars"] == len(text)
    metadata = json.loads((tmp_path / "aozora_000148_789_ruby_5639.txt.source.json").read_text(encoding="utf-8"))
    assert metadata["url"].endswith("789_ruby_5639.zip")
    assert metadata["reused_existing"] is False


def test_main_supports_url_manifest_and_writes_relative_manifest(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    payload = _aozora_zip_bytes()
    monkeypatch.setattr(
        p1_prepare_aozora.urllib.request,
        "build_opener",
        lambda *handlers: _StaticOpener(payload),
    )
    out_dir = tmp_path / "prepared"
    url_manifest = tmp_path / "urls.txt"
    corpus_manifest = tmp_path / "nested" / "corpora.txt"
    report_json = tmp_path / "nested" / "reports" / "report.json"
    url_manifest.write_text(
        "# comment\nhttps://www.aozora.gr.jp/cards/000148/files/789_ruby_5639.zip\n",
        encoding="utf-8",
    )
    rc = p1_prepare_aozora.main(
        [
            "--out-dir",
            str(out_dir),
            "--url-manifest",
            str(url_manifest),
            "--write-manifest",
            str(corpus_manifest),
            "--json",
            str(report_json),
        ]
    )
    assert rc == 0
    assert corpus_manifest.read_text(encoding="utf-8") == (
        "# Generated by scripts/p1_prepare_aozora.py\n"
        "../prepared/aozora_000148_789_ruby_5639.txt\n"
    )
    payload_json = json.loads(report_json.read_text(encoding="utf-8"))
    bundle_payload = json.loads(
        corpus_manifest.with_suffix(".txt.bundle.json").read_text(encoding="utf-8")
    )
    assert bundle_payload["generated_by"] == "scripts/p1_prepare_aozora.py"
    assert bundle_payload["bundle"]["files"][0]["sha256"] == payload_json["records"][0]["sha256"]
    assert bundle_payload["bundle"]["combined"]["includes_base"] is False
    assert payload_json["records"][0]["url"].endswith("789_ruby_5639.zip")


