def test_prepare_aozora_corpora_is_batch_atomic_on_second_corpus_commit_failure(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    payload = _aozora_zip_bytes()

    class _StaticBatchOpener:
        def open(self, url: str, timeout: float = 30.0) -> _FakeResponse:
            return _FakeResponse(payload)

    real_replace = os.replace
    corpus_replace_count = 0

    def _failing_replace(src: os.PathLike[str] | str, dst: os.PathLike[str] | str) -> None:
        nonlocal corpus_replace_count
        dst_path = Path(dst)
        if dst_path.name.endswith(".txt") and not dst_path.name.endswith(".source.json"):
            corpus_replace_count += 1
            if corpus_replace_count == 2:
                raise OSError("boom on second corpus commit")
        real_replace(src, dst)

    monkeypatch.setattr(
        p1_prepare_aozora.urllib.request,
        "build_opener",
        lambda *handlers: _StaticBatchOpener(),
    )
    monkeypatch.setattr(p1_prepare_aozora.os, "replace", _failing_replace)
    with pytest.raises(OSError, match="second corpus commit"):
        p1_prepare_aozora.prepare_aozora_corpora(
            [
                "https://www.aozora.gr.jp/cards/000148/files/789_ruby_5639.zip",
                "https://www.aozora.gr.jp/cards/000149/files/other_1.zip",
            ],
            out_dir=tmp_path,
        )
    assert not list(tmp_path.glob("*.txt"))
    assert not list(tmp_path.glob("*.source.json"))
    assert not list(tmp_path.glob("*.tmp"))


