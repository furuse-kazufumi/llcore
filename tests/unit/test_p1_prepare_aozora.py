def test_download_aozora_text_rejects_redirects(monkeypatch: pytest.MonkeyPatch) -> None:
    class _RedirectingOpener:
        def __init__(self, handlers: tuple[object, ...]) -> None:
            self._handlers = handlers

        def open(self, url: str, timeout: float = 30.0) -> _FakeResponse:
            redirect_handler = next(
                handler
                for handler in self._handlers
                if isinstance(handler, p1_prepare_aozora._NoRedirectHandler)
            )
            redirect_handler.redirect_request(
                req=None,
                fp=None,
                code=302,
                msg="Found",
                headers=Message(),
                newurl="https://evil.example.com/redirected.zip",
            )
            raise AssertionError("redirect handler should have raised")

    monkeypatch.setattr(
        p1_prepare_aozora.urllib.request,
        "build_opener",
        lambda *handlers: _RedirectingOpener(handlers),
    )
    with pytest.raises(ValueError, match="redirects are not allowed"):
        p1_prepare_aozora._download_aozora_text(  # pyright: ignore[reportPrivateUsage]
            "https://www.aozora.gr.jp/cards/000148/files/789_ruby_5639.zip",
            timeout=30.0,
        )


def test_script_entrypoint_runs_via_subprocess(tmp_path: Path) -> None:
    payload_file = tmp_path / "payload.zip"
    payload_file.write_bytes(_aozora_zip_bytes())
    bootstrap = (
        "import os, runpy, urllib.request\n"
        "from pathlib import Path\n"
        "payload = Path(os.environ['AOZORA_TEST_PAYLOAD']).read_bytes()\n"
        "class Resp:\n"
        "    def __init__(self, data): self._data = data\n"
        "    def read(self): return self._data\n"
        "    def __enter__(self): return self\n"
        "    def __exit__(self, exc_type, exc, tb): return None\n"
        "class Opener:\n"
        "    def open(self, url, timeout=30.0): return Resp(payload)\n"
        "urllib.request.build_opener = lambda *handlers: Opener()\n"
        "runpy.run_path('scripts/p1_prepare_aozora.py', run_name='__main__')\n"
    )
    out_dir = tmp_path / "prepared"
    proc = subprocess.run(
        [
            sys.executable,
            "-c",
            bootstrap,
            "--out-dir",
            str(out_dir),
            "https://www.aozora.gr.jp/cards/000148/files/789_ruby_5639.zip",
        ],
        cwd=Path(__file__).resolve().parents[2],
        env={**os.environ, "AOZORA_TEST_PAYLOAD": str(payload_file)},
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr
    assert (out_dir / "aozora_000148_789_ruby_5639.txt").exists()
